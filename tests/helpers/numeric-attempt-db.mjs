import {PGlite} from '@electric-sql/pglite';
import fs from 'node:fs';
export async function createAttemptDb(){
  const db=new PGlite();
  await db.exec(`create role authenticated;create schema auth;create schema private;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
    create function private.is_allowed_user() returns boolean language sql stable as $$select coalesce(current_setting('test.allowed',true),'')='true'$$;
    create table exercise_attempts(
      id uuid primary key default gen_random_uuid(),user_id uuid not null,exercise_id text not null,run_id uuid not null,
      attempt_no integer generated by default as identity,score integer,total_questions integer,accuracy numeric,started_at timestamptz,
      completed_at timestamptz default clock_timestamp(),correct_count integer,wrong_count integer,unanswered_count integer,
      bookmarked_count integer,duration_seconds integer,answers_status jsonb,selected_answers jsonb,bookmarks jsonb,
      question_snapshot jsonb,context_snapshot jsonb,submitted_from text,
      unique(user_id,exercise_id,run_id),constraint exercise_attempts_counts_check check(score=correct_count and correct_count+wrong_count+unanswered_count=total_questions));
    alter table exercise_attempts enable row level security;
    create policy own_attempts on exercise_attempts to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
    grant usage on schema public,auth,private to authenticated;
    grant all on exercise_attempts to authenticated;grant usage,select on all sequences in schema public to authenticated;`);
  await db.exec(fs.readFileSync('supabase/migrations/20261018232728_numeric_attempt_grading.sql','utf8'));
  const owner='11111111-1111-4111-8111-111111111111';
  await db.query("select set_config('test.uid',$1,false),set_config('test.allowed','true',false)",[owner]);
  await db.exec('set role authenticated');
  const record=async body=>{
    const fields=['exercise_id','run_id','started_at','score','total_questions','correct_count','wrong_count','unanswered_count','bookmarked_count','duration_seconds','answers_status','selected_answers','bookmarks','question_snapshot','context_snapshot','submitted_from'];
    const values=fields.map(field=>typeof body['p_'+field]==='object'?JSON.stringify(body['p_'+field]):body['p_'+field]);
    return (await db.query('select * from public.record_exercise_attempt('+fields.map((_,i)=>'$'+(i+1)).join(',')+')',values)).rows;
  };
  return {db,record,owner};
}

import assert from 'node:assert/strict';
import {createChatDrafts} from '../assets/chat-drafts.js';
const data=new Map(),storage={getItem:key=>data.get(key),setItem:(key,value)=>data.set(key,value)};
const drafts=createChatDrafts('owner-a',storage),file={name:'bài tập.png',size:1200};
const sent={text:'Nội dung phòng A',type:'assignment',file,replyTo:1,editingId:null};
drafts.put('room-a',sent);drafts.put('room-b',{text:'Nội dung phòng B'});drafts.flush();
assert.equal(drafts.get('room-b').file,null);
assert.equal(drafts.get('room-a').file,file);
assert.equal(drafts.get('room-a').type,'assignment');
assert.equal(createChatDrafts('owner-b',storage).get('room-a').text,'');
const reloaded=createChatDrafts('owner-a',storage).get('room-a');
assert.equal(reloaded.text,sent.text);assert.equal(reloaded.file,null);
assert.equal(reloaded.attachment.name,file.name,'Reload silently lost the attachment reminder');
assert.equal(reloaded.replyTo,1);
drafts.consume('room-a',sent,{sticker:true});
assert.equal(drafts.get('room-a').text,sent.text);assert.equal(drafts.get('room-a').file,file);
assert.equal(drafts.get('room-a').replyTo,null);
drafts.put('room-a',{...sent,text:'Soạn tiếp trong lúc gửi',file:{name:'next.txt',size:2},replyTo:2});
drafts.consume('room-a',sent);
assert.equal(drafts.get('room-a').text,'Soạn tiếp trong lúc gửi');
assert.equal(drafts.get('room-a').file.name,'next.txt');assert.equal(drafts.get('room-a').replyTo,2);
assert.equal(drafts.get('room-b').text,'Nội dung phòng B');
drafts.put('room-a',sent);drafts.consume('room-a',sent);
assert.equal(createChatDrafts('owner-a',storage).get('room-a').text,'','Returning to a sent room restored a stale draft');
assert.equal(createChatDrafts('owner-a',storage).get('room-b').text,'Nội dung phòng B');
const blocked=createChatDrafts('owner-c',{getItem(){throw Error('blocked')},setItem(){throw Error('quota')}});
blocked.put('room-a',sent);blocked.flush();assert.equal(blocked.get('room-a').file,file);
for(let i=0;i<60;i++)drafts.put('extra-'+i,{text:'x'.repeat(9000)});
drafts.flush();assert.equal(JSON.parse(data.get('lms-chat-drafts-v1:owner-a')).length,50);
assert.equal(drafts.get('extra-59').text.length,8000);
console.log('PASS: room/account draft isolation, attachment recovery, late sends, sticker preservation and unavailable storage.');
